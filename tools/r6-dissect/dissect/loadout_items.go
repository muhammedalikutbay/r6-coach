package dissect

// Game item IDs of each operator's loadout (R6Koc patch 5).
//
// The asset ID in a kill packet (weaponId) is not the game item ID that public name tables
// (e.g. wnc-replay/replay-tool `analysis/names.go`) use. The replay also holds one loadout block
// per operator, with game item IDs per slot (record layout from wnc-replay/replay-tool
// `analysis/events.go` ExtractLoadouts, MIT; block start found for R6Koc on Y11S3):
//
//	7A8AC28F <operator id u64>             block start
//	<item id u64> <slot hash u32> <cat u32> one record per slot, within ~360 bytes
//
// Slot hashes are CRC32s of the slot names; cat is 10 (weapon) or 3 (gadget). A kill's game item
// ID is the item in the killer operator's block for the slot that holds the kill weapon.
// Block operator IDs are game item IDs, not dissect operator IDs, so blocks are matched to
// players by operator name (game_operators.go, generated by tools/gen-weapons).

import (
	"bytes"
	"encoding/binary"
	"strings"

	"github.com/rs/zerolog/log"
)

var operatorBlockField = []byte{0x7A, 0x8A, 0xC2, 0x8F}

const (
	slotHashPrimary   uint32 = 3268402276 // "PrimaryWeapon"
	slotHashSecondary uint32 = 1893246388 // "SecondaryWeapon"
	slotHashGadget    uint32 = 2947831256 // "SecondaryGadget"
	slotHashAbility   uint32 = 497232904  // "OperatorGadget"
	itemCatWeapon     uint32 = 10
	itemCatGadget     uint32 = 3
	operatorBlockSpan        = 420 // records end ~+372; the next block starts ~+490
)

func slotHash(s WeaponSlot) uint32 {
	switch s {
	case PrimarySlot:
		return slotHashPrimary
	case SecondarySlot:
		return slotHashSecondary
	case GadgetSlot:
		return slotHashGadget
	case AbilitySlot:
		return slotHashAbility
	}
	return 0
}

// validItemID mirrors the upstream ID check: 5 significant bytes, none above.
func validItemID(id uint64) bool {
	return id != 0 && id>>40 == 0 && (id>>32)&0xFF != 0
}

// readOperatorBlock records the item IDs of one operator loadout block. It only peeks at r.b
// and never fails.
func readOperatorBlock(r *Reader) error {
	if r.inventory == nil {
		return nil
	}
	start := patternStart(r, operatorBlockField)
	if start < 0 || r.offset+8 > len(r.b) {
		return nil
	}
	op := binary.LittleEndian.Uint64(r.b[r.offset : r.offset+8])
	if !validItemID(op) {
		return nil
	}
	name, ok := gameOperatorNames[op]
	if !ok {
		log.Debug().Uint64("op", op).Msg("loadout block for an unknown game operator id")
		return nil
	}
	end := start + operatorBlockSpan
	if end > len(r.b) {
		end = len(r.b)
	}
	if next := bytes.Index(r.b[r.offset:end], operatorBlockField); next >= 0 {
		end = r.offset + next
	}
	for o := r.offset + 8; o+16 <= end; o++ {
		hash := binary.LittleEndian.Uint32(r.b[o+8 : o+12])
		switch hash {
		case slotHashPrimary, slotHashSecondary, slotHashGadget, slotHashAbility:
		default:
			continue
		}
		cat := binary.LittleEndian.Uint32(r.b[o+12 : o+16])
		item := binary.LittleEndian.Uint64(r.b[o : o+8])
		if (cat != itemCatWeapon && cat != itemCatGadget) || !validItemID(item) {
			continue
		}
		key := operatorSlot{operatorKey(name), hash}
		known := false
		for _, v := range r.inventory.operatorItems[key] {
			known = known || v == item
		}
		if !known {
			r.inventory.operatorItems[key] = append(r.inventory.operatorItems[key], item)
		}
	}
	return nil
}

type operatorSlot struct {
	op   string // operatorKey of the operator name
	slot uint32
}

// operatorKey normalizes an operator name: "Capitao" and "CAPITAO" give the same key.
func operatorKey(name string) string {
	return strings.Map(func(c rune) rune {
		switch {
		case c >= 'a' && c <= 'z':
			return c - 'a' + 'A'
		case c >= 'A' && c <= 'Z', c >= '0' && c <= '9':
			return c
		}
		return -1
	}, name)
}

// itemID returns the game item ID the operator carried in the slot, or 0 when it is unknown
// or ambiguous (more than one block with different items).
func (r *Reader) itemID(op Operator, s WeaponSlot) uint64 {
	if r.inventory == nil {
		return 0
	}
	items := r.inventory.operatorItems[operatorSlot{operatorKey(op.String()), slotHash(s)}]
	if len(items) != 1 {
		return 0
	}
	return items[0]
}
